using System.ComponentModel.DataAnnotations;
using System.ComponentModel.DataAnnotations.Schema;

namespace smss_api_db_layer.entity
{
    /// <summary>
    /// One row for every staff member (Principal, Teacher, Accountant, ...). What they may do in the system is decided by the roles on their
    /// login (tb_user_roles), never by this table. status_id is "hide this row" (Active / Inactive); employment_status_id is the real-world status.
    /// </summary>
    [Table("tb_employees", Schema = "public")]
    public class TbEmployee
    {
        // Business id, e.g. DPS001EM001 ({school short code}EM{nnn}): generated by the app once, reused as the login id (tb_users.org_user_id).
        [Key][DatabaseGenerated(DatabaseGeneratedOption.None)][Column("employee_id")][StringLength(20)]
        public string EmployeeId { get; set; } = null!;
        [Column("school_id")][StringLength(100)] public string SchoolId { get; set; } = null!;
        [Column("designation_id")] public long DesignationId { get; set; }
        [Column("department_id")] public long DepartmentId { get; set; }
        [Column("employment_status_id")] public long EmploymentStatusId { get; set; }
        /// <summary>Teaching or Non-Teaching.</summary>
        [Column("employee_type")][StringLength(20)] public string EmployeeType { get; set; } = null!;
        [Column("first_name")][StringLength(100)] public string FirstName { get; set; } = null!;
        [Column("middle_name")][StringLength(100)] public string? MiddleName { get; set; }
        [Column("last_name")][StringLength(100)] public string LastName { get; set; } = null!;
        [Column("gender_id")] public long? GenderId { get; set; }
        [Column("blood_group_id")] public long? BloodGroupId { get; set; }
        [Column("date_of_birth", TypeName = "date")] public DateOnly DateOfBirth { get; set; }
        [Column("email")][StringLength(150)] public string? Email { get; set; }
        [Column("mobile_number")][StringLength(20)] public string MobileNumber { get; set; } = null!;
        [Column("alternate_mobile")][StringLength(20)] public string? AlternateMobile { get; set; }
        [Column("address")] public string Address { get; set; } = null!;
        [Column("date_of_joining", TypeName = "date")] public DateOnly DateOfJoining { get; set; }
        [Column("date_of_leaving", TypeName = "date")] public DateOnly? DateOfLeaving { get; set; }
        [Column("qualification")] public string? Qualification { get; set; }
        /// <summary>Relative public URL of the photo (/uploads/...); null = none.</summary>
        [Column("photo_path")] public string? PhotoPath { get; set; }
        [Column("status_id")] public int StatusId { get; set; }
        [Column("created_at")] public DateTime CreatedAt { get; set; }
        [Column("updated_at")] public DateTime UpdatedAt { get; set; }
    }
}
