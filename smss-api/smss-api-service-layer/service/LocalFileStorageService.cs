using Microsoft.Extensions.Logging;
using smss_api_service_layer.helper;
using smss_api_service_layer.@interface;

namespace smss_api_service_layer.service
{
    public class LocalFileStorageService : IFileStorageService
    {
        private readonly string _rootPath;       // absolute folder on disk
        private readonly string _requestPath;    // public URL prefix, e.g. "/uploads"
        private readonly string _privateRootPath; // absolute folder for files that must never be served by URL
        private readonly ILogger<LocalFileStorageService> _logger;

        public LocalFileStorageService(string rootPath, string requestPath, string privateRootPath, ILogger<LocalFileStorageService> logger)
        {
            _rootPath = Path.GetFullPath(rootPath);
            _privateRootPath = Path.GetFullPath(privateRootPath);
            _requestPath = requestPath.TrimEnd('/');
            _logger = logger;
        }

        public async Task<string> SaveSchoolLogoAsync(string schoolCode, Stream content, string extension, CancellationToken ct)
        {
            if (!SchoolCodeRules.IsFolderSafe(schoolCode))
                throw new InvalidOperationException("School code is not a valid folder name.");

            var folder = Path.Combine(_rootPath, schoolCode, "logo");
            Directory.CreateDirectory(folder);

            var fileName = $"logo_{DateTime.UtcNow:yyyyMMddHHmmssfff}{extension}";
            var fullPath = Path.Combine(folder, fileName);

            await using var fs = new FileStream(fullPath, FileMode.CreateNew, FileAccess.Write, FileShare.None, 81920, useAsync: true);
            await content.CopyToAsync(fs, ct);

            return $"{_requestPath}/{schoolCode}/logo/{fileName}";
        }

        public async Task<string> SaveStudentPhotoAsync(string schoolCode, string studentId, Stream content, string extension, CancellationToken ct)
        {
            if (!SchoolCodeRules.IsFolderSafe(schoolCode))
                throw new InvalidOperationException("School code is not a valid folder name.");

            // The id is generated by the app (short code + "ST" + digits), but it is used as a folder name, so check it
            if (string.IsNullOrEmpty(studentId) || studentId.Length > 20 || !studentId.All(char.IsAsciiLetterOrDigit))
                throw new InvalidOperationException("Student id is not a valid folder name.");
            var studentFolder = studentId;
            var folder = Path.Combine(_rootPath, schoolCode, "students", studentFolder);
            Directory.CreateDirectory(folder);

            var fileName = $"photo_{DateTime.UtcNow:yyyyMMddHHmmssfff}{extension}";
            var fullPath = Path.Combine(folder, fileName);

            await using var fs = new FileStream(fullPath, FileMode.CreateNew, FileAccess.Write, FileShare.None, 81920, useAsync: true);
            await content.CopyToAsync(fs, ct);

            return $"{_requestPath}/{schoolCode}/students/{studentFolder}/{fileName}";
        }

        private static void EnsureSafeIds(string schoolCode, string employeeId)
        {
            if (!SchoolCodeRules.IsFolderSafe(schoolCode))
                throw new InvalidOperationException("School code is not a valid folder name.");
            // The id is generated by the app (short code + "EM" + digits) but is used as a folder name, so check it
            if (string.IsNullOrEmpty(employeeId) || employeeId.Length > 20 || !employeeId.All(char.IsAsciiLetterOrDigit))
                throw new InvalidOperationException("Employee id is not a valid folder name.");
        }

        public async Task<string> SaveEmployeePhotoAsync(string schoolCode, string employeeId, Stream content, string extension, CancellationToken ct)
        {
            EnsureSafeIds(schoolCode, employeeId);
            var folder = Path.Combine(_rootPath, schoolCode, "employees", employeeId);
            Directory.CreateDirectory(folder);

            var fileName = $"photo_{DateTime.UtcNow:yyyyMMddHHmmssfff}{extension}";
            await using var fs = new FileStream(Path.Combine(folder, fileName), FileMode.CreateNew, FileAccess.Write, FileShare.None, 81920, useAsync: true);
            await content.CopyToAsync(fs, ct);

            return $"{_requestPath}/{schoolCode}/employees/{employeeId}/{fileName}";
        }

        public async Task<string> SaveEmployeeDocumentAsync(string schoolCode, string employeeId, Stream content, string extension, CancellationToken ct)
        {
            EnsureSafeIds(schoolCode, employeeId);
            var folder = Path.Combine(_privateRootPath, schoolCode, "employees", employeeId, "documents");
            Directory.CreateDirectory(folder);

            // random name: nothing about the file can be guessed, and the client's file name is never used on disk
            var fileName = $"doc_{Guid.NewGuid():N}{extension}";
            await using var fs = new FileStream(Path.Combine(folder, fileName), FileMode.CreateNew, FileAccess.Write, FileShare.None, 81920, useAsync: true);
            await content.CopyToAsync(fs, ct);

            return $"{schoolCode}/employees/{employeeId}/documents/{fileName}";
        }

        public async Task<string> SaveHomeworkAttachmentAsync(string schoolCode, long homeworkId, Stream content, string extension, CancellationToken ct)
        {
            if (!SchoolCodeRules.IsFolderSafe(schoolCode)) throw new InvalidOperationException("School code is not a valid folder name.");
            if (homeworkId <= 0) throw new InvalidOperationException("Homework id is not valid.");
            var folder = Path.Combine(_privateRootPath, schoolCode, "homework", homeworkId.ToString());
            Directory.CreateDirectory(folder);

            var fileName = $"attachment_{DateTime.UtcNow:yyyyMMddHHmmssfff}{extension}";
            await using var fs = new FileStream(Path.Combine(folder, fileName), FileMode.CreateNew, FileAccess.Write, FileShare.None, 81920, useAsync: true);
            await content.CopyToAsync(fs, ct);

            return $"{schoolCode}/homework/{homeworkId}/{fileName}";
        }

        public async Task<string> SaveAdmissionDocumentAsync(string schoolCode, long admissionId, Stream content, string extension, CancellationToken ct)
        {
            if (!SchoolCodeRules.IsFolderSafe(schoolCode)) throw new InvalidOperationException("School code is not a valid folder name.");
            if (admissionId <= 0) throw new InvalidOperationException("Admission id is not valid.");
            var folder = Path.Combine(_privateRootPath, schoolCode, "admissions", admissionId.ToString(), "documents");
            Directory.CreateDirectory(folder);

            // random name: nothing about the file can be guessed, and the client file name is never used on disk
            var fileName = $"doc_{Guid.NewGuid():N}{extension}";
            await using var fs = new FileStream(Path.Combine(folder, fileName), FileMode.CreateNew, FileAccess.Write, FileShare.None, 81920, useAsync: true);
            await content.CopyToAsync(fs, ct);

            return $"{schoolCode}/admissions/{admissionId}/documents/{fileName}";
        }

        public Stream? OpenPrivate(string storageKey)
        {
            try
            {
                var fullPath = Path.GetFullPath(Path.Combine(_privateRootPath, storageKey.Replace('/', Path.DirectorySeparatorChar)));
                // Never open anything outside the private root
                if (!fullPath.StartsWith(_privateRootPath + Path.DirectorySeparatorChar, StringComparison.Ordinal) || !File.Exists(fullPath)) return null;
                return new FileStream(fullPath, FileMode.Open, FileAccess.Read, FileShare.Read, 81920, useAsync: true);
            }
            catch (Exception ex)
            {
                _logger.LogWarning(ex, "Could not open private file {Key}", storageKey);
                return null;
            }
        }

        public void DeletePrivate(string storageKey)
        {
            try
            {
                var fullPath = Path.GetFullPath(Path.Combine(_privateRootPath, storageKey.Replace('/', Path.DirectorySeparatorChar)));
                if (!fullPath.StartsWith(_privateRootPath + Path.DirectorySeparatorChar, StringComparison.Ordinal)) return;
                if (File.Exists(fullPath)) File.Delete(fullPath);
            }
            catch (Exception ex)
            {
                _logger.LogWarning(ex, "Could not delete private file {Key}", storageKey);
            }
        }

        public void Delete(string relativeUrl)
        {
            try
            {
                if (!relativeUrl.StartsWith(_requestPath + "/", StringComparison.Ordinal)) return;

                var relative = relativeUrl[(_requestPath.Length + 1)..].Replace('/', Path.DirectorySeparatorChar);
                var fullPath = Path.GetFullPath(Path.Combine(_rootPath, relative));

                // Never delete anything outside the uploads root
                if (!fullPath.StartsWith(_rootPath + Path.DirectorySeparatorChar, StringComparison.Ordinal)) return;

                if (File.Exists(fullPath)) File.Delete(fullPath);
            }
            catch (Exception ex)
            {
                _logger.LogWarning(ex, "Could not delete file {Url}", relativeUrl);
            }
        }
    }
}