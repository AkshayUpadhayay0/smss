using Microsoft.Extensions.Logging;
using smss_api_service_layer.helper;
using smss_api_service_layer.@interface;

namespace smss_api_service_layer.service
{
    public class LocalFileStorageService : IFileStorageService
    {
        private readonly string _rootPath;       // absolute folder on disk
        private readonly string _requestPath;    // public URL prefix, e.g. "/uploads"
        private readonly string _privateRootPath; // absolute folder for files that must never be served by URL
        private readonly ILogger<LocalFileStorageService> _logger;

        public LocalFileStorageService(string rootPath, string requestPath, string privateRootPath, ILogger<LocalFileStorageService> logger)
        {
            _rootPath = Path.GetFullPath(rootPath);
            _privateRootPath = Path.GetFullPath(privateRootPath);
            _requestPath = requestPath.TrimEnd('/');
            _logger = logger;
        }

        public async Task<string> SaveSchoolLogoAsync(string schoolCode, Stream content, string extension, CancellationToken ct)
        {
            if (!SchoolCodeRules.IsFolderSafe(schoolCode))
                throw new InvalidOperationException("School code is not a valid folder name.");

            var folder = Path.Combine(_rootPath, schoolCode, "logo");
            Directory.CreateDirectory(folder);

            var fileName = $"logo_{DateTime.UtcNow:yyyyMMddHHmmssfff}{extension}";
            var fullPath = Path.Combine(folder, fileName);

            await using var fs = new FileStream(fullPath, FileMode.CreateNew, FileAccess.Write, FileShare.None, 81920, useAsync: true);
            await content.CopyToAsync(fs, ct);

            return $"{_requestPath}/{schoolCode}/logo/{fileName}";
        }

        public async Task<string> SaveStudentPhotoAsync(string schoolCode, string studentId, Stream content, string extension, CancellationToken ct)
        {
            if (!SchoolCodeRules.IsFolderSafe(schoolCode))
                throw new InvalidOperationException("School code is not a valid folder name.");

            // The id is generated by the app (short code + "ST" + digits), but it is used as a folder name, so check it
            if (string.IsNullOrEmpty(studentId) || studentId.Length > 20 || !studentId.All(char.IsAsciiLetterOrDigit))
                throw new InvalidOperationException("Student id is not a valid folder name.");
            var studentFolder = studentId;
            var folder = Path.Combine(_privateRootPath, schoolCode, "students", studentFolder);
            Directory.CreateDirectory(folder);

            var fileName = $"photo_{DateTime.UtcNow:yyyyMMddHHmmssfff}{extension}";
            var fullPath = Path.Combine(folder, fileName);

            await using var fs = new FileStream(fullPath, FileMode.CreateNew, FileAccess.Write, FileShare.None, 81920, useAsync: true);
            await content.CopyToAsync(fs, ct);

            return $"{schoolCode}/students/{studentFolder}/{fileName}";
        }

        private static void EnsureSafeIds(string schoolCode, string employeeId)
        {
            if (!SchoolCodeRules.IsFolderSafe(schoolCode))
                throw new InvalidOperationException("School code is not a valid folder name.");
            // The id is generated by the app (short code + "EM" + digits) but is used as a folder name, so check it
            if (string.IsNullOrEmpty(employeeId) || employeeId.Length > 20 || !employeeId.All(char.IsAsciiLetterOrDigit))
                throw new InvalidOperationException("Employee id is not a valid folder name.");
        }

