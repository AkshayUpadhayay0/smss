-- Employee Management: ONE table for every staff member (Principal, Teacher, Accountant, ...). What an employee may DO in the system is
-- decided by the roles on their login (tb_user_roles), exactly like School Admin; the designation is only a job title.
--
-- Adds: lut_employment_status (global, seeded), tb_employees, tb_employee_documents.
-- Needs the existing tb_schools, lut_status, lut_gender, lut_blood_group, tb_employee_designations, tb_employee_departments,
-- tb_document_types, tb_users. Run BEFORE starting the API build that contains these entities. Safe to run twice.
--
-- Decisions (see the Employee module notes):
--  * "Hide this row" is status_id -> lut_status (Active / Inactive, stype 'general status'), the pattern of tb_students, the designation /
--    department / document-type masters. It is INDEPENDENT of employment_status_id (the real-world status: Active, On Leave, Resigned,
--    Terminated, Retired): a resigned employee stays visible for history; an Inactive row is a duplicate / mistake.
--  * A login works only while BOTH switches say enabled: the row is Active (status_id) AND the employment status does not block login
--    (lut_employment_status.blocks_login: Resigned / Terminated / Retired do; Active / On Leave do not). The app recomputes the login's status
--    from both whenever either changes, so reverting one switch never re-enables a login the other one is holding off.
--  * employee_id is a varchar(20) business id {school short code}EM{nnn} (e.g. DPS001EM001), generated by the app like student_id, and reused
--    as the employee's login id (tb_users.org_user_id) when a login is created.
--  * gender_id / blood_group_id are bigint FKs to lut_gender / lut_blood_group (the key type those tables really use).
--  * Employee documents are stored OUTSIDE the public uploads folder and served only through an authenticated endpoint; the table keeps the
--    storage key (document_path), never a public URL.

BEGIN;

-- 1. lut_employment_status: global lookup (same shape as lut_gender)
CREATE TABLE IF NOT EXISTS public.lut_employment_status
(
    employment_status_id bigint       GENERATED ALWAYS AS IDENTITY,
    status_code          varchar(30)  NOT NULL,
    status_name          varchar(50)  NOT NULL,
    description          varchar(250),
    is_active            boolean      NOT NULL DEFAULT true,
    blocks_login         boolean      NOT NULL DEFAULT false,   -- true: an employee in this status cannot sign in (Resigned, Terminated, Retired)
    created_at           timestamptz  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at           timestamptz  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT lut_employment_status_pkey PRIMARY KEY (employment_status_id),
    CONSTRAINT uq_lut_employment_status_code UNIQUE (status_code),
    CONSTRAINT uq_lut_employment_status_name UNIQUE (status_name)
);

-- (for a database that already ran an earlier version of this file: add the column, and set it for the three leaving statuses ONLY that once)
DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM information_schema.columns WHERE table_schema = 'public' AND table_name = 'lut_employment_status' AND column_name = 'blocks_login') THEN
        ALTER TABLE public.lut_employment_status ADD COLUMN blocks_login boolean NOT NULL DEFAULT false;
        UPDATE public.lut_employment_status SET blocks_login = true WHERE status_code IN ('RESIGNED', 'TERMINATED', 'RETIRED');
    END IF;
END $$;

INSERT INTO public.lut_employment_status (status_code, status_name, description, blocks_login) VALUES
    ('ACTIVE',     'Active',     'Currently working at the school',        false),
    ('ON_LEAVE',   'On Leave',   'Away on long leave and expected back',   false),
    ('RESIGNED',   'Resigned',   'Left by their own decision',             true),
    ('TERMINATED', 'Terminated', 'Service ended by the school',            true),
    ('RETIRED',    'Retired',    'Retired from service',                   true)
ON CONFLICT (status_code) DO NOTHING;

-- 2. tb_employees
CREATE TABLE IF NOT EXISTS public.tb_employees
(
    employee_id          varchar(20)   NOT NULL,
    school_id            varchar(100)  NOT NULL,
    designation_id       bigint        NOT NULL,
    department_id        bigint        NOT NULL,
    employment_status_id bigint        NOT NULL,
    employee_type        varchar(20)   NOT NULL,
    first_name           varchar(100)  NOT NULL,
    middle_name          varchar(100),
    last_name            varchar(100)  NOT NULL,
    gender_id            bigint,
    blood_group_id       bigint,
    date_of_birth        date          NOT NULL,
    email                varchar(150),
    mobile_number        varchar(20)   NOT NULL,
    alternate_mobile     varchar(20),
    address              text          NOT NULL,
    date_of_joining      date          NOT NULL,
    date_of_leaving      date,
    qualification        text,
    photo_path           text,
    status_id            integer       NOT NULL,
    created_at           timestamptz   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at           timestamptz   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT tb_employees_pkey PRIMARY KEY (employee_id),
    CONSTRAINT fk_tb_employees_school            FOREIGN KEY (school_id)            REFERENCES public.tb_schools (school_id),
    CONSTRAINT fk_tb_employees_designation       FOREIGN KEY (designation_id)       REFERENCES public.tb_employee_designations (designation_id),
    CONSTRAINT fk_tb_employees_department        FOREIGN KEY (department_id)        REFERENCES public.tb_employee_departments (department_id),
    CONSTRAINT fk_tb_employees_employment_status FOREIGN KEY (employment_status_id) REFERENCES public.lut_employment_status (employment_status_id),
    CONSTRAINT fk_tb_employees_gender            FOREIGN KEY (gender_id)            REFERENCES public.lut_gender (gender_id),
    CONSTRAINT fk_tb_employees_blood_group       FOREIGN KEY (blood_group_id)       REFERENCES public.lut_blood_group (blood_group_id),
    CONSTRAINT fk_tb_employees_status            FOREIGN KEY (status_id)            REFERENCES public.lut_status (sid),
    CONSTRAINT chk_tb_employees_type  CHECK (employee_type IN ('Teaching', 'Non-Teaching')),
    CONSTRAINT chk_tb_employees_dates CHECK (date_of_joining >= date_of_birth AND (date_of_leaving IS NULL OR date_of_leaving >= date_of_joining))
);
CREATE INDEX IF NOT EXISTS idx_tb_employees_school_id   ON public.tb_employees (school_id);
CREATE INDEX IF NOT EXISTS idx_tb_employees_designation ON public.tb_employees (designation_id);
CREATE INDEX IF NOT EXISTS idx_tb_employees_department  ON public.tb_employees (department_id);
CREATE INDEX IF NOT EXISTS idx_tb_employees_emp_status  ON public.tb_employees (employment_status_id);
CREATE INDEX IF NOT EXISTS idx_tb_employees_status_id   ON public.tb_employees (status_id);
-- an email belongs to one employee per school (blank emails are stored as NULL, so they never clash)
CREATE UNIQUE INDEX IF NOT EXISTS uq_tb_employees_school_email ON public.tb_employees (school_id, lower(email)) WHERE email IS NOT NULL;

-- 3. tb_employee_documents: ID proofs, certificates, ... (the document type comes from the school's tb_document_types, applies_to EMPLOYEE / BOTH)
CREATE TABLE IF NOT EXISTS public.tb_employee_documents
(
    employee_document_id bigint        GENERATED ALWAYS AS IDENTITY,
    employee_id          varchar(20)   NOT NULL,
    school_id            varchar(100)  NOT NULL,
    document_type_id     bigint        NOT NULL,
    document_path        text          NOT NULL,   -- storage key in the PRIVATE store, e.g. SCH001/employees/DPS001EM001/documents/<file>
    original_file_name   varchar(255)  NOT NULL,
    content_type         varchar(100)  NOT NULL,
    file_size            bigint        NOT NULL,
    remarks              text,
    uploaded_by          bigint,                   -- tb_users.user_id, from the token
    status_id            integer       NOT NULL,   -- Active / Inactive (a removed document is kept, not deleted)
    created_at           timestamptz   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at           timestamptz   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT tb_employee_documents_pkey PRIMARY KEY (employee_document_id),
    CONSTRAINT fk_tb_employee_documents_employee      FOREIGN KEY (employee_id)      REFERENCES public.tb_employees (employee_id),
    CONSTRAINT fk_tb_employee_documents_school        FOREIGN KEY (school_id)        REFERENCES public.tb_schools (school_id),
    CONSTRAINT fk_tb_employee_documents_type          FOREIGN KEY (document_type_id) REFERENCES public.tb_document_types (document_type_id),
    CONSTRAINT fk_tb_employee_documents_uploaded_by   FOREIGN KEY (uploaded_by)      REFERENCES public.tb_users (user_id),
    CONSTRAINT fk_tb_employee_documents_status        FOREIGN KEY (status_id)        REFERENCES public.lut_status (sid),
    CONSTRAINT chk_tb_employee_documents_size CHECK (file_size > 0)
);
CREATE INDEX IF NOT EXISTS idx_tb_employee_documents_employee ON public.tb_employee_documents (employee_id);
CREATE INDEX IF NOT EXISTS idx_tb_employee_documents_school   ON public.tb_employee_documents (school_id);

COMMIT;
