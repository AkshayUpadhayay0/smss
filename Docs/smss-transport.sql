-- Transport module, stage 1: areas, vehicles, drivers (web + API only; no student assignment, stops, live location or fee wiring yet).
--
-- Creates (all in schema public):
--   lut_vehicle_type        global lookup, seeded Bus / Van / Car / Other (extendable: add rows, never ids in code)
--   lut_vehicle_ownership   global lookup, seeded Own / Rented
--   tb_transport_areas      school-owned: area name, distance (km), transport fee (NUMERIC(10,2)), remarks, status
--   tb_vehicles             school-owned: label ("Bus 3"), registration plate, type, ownership, model year, seating capacity,
--                           rented owner name/contact, last service date, PUC expiry, insurance expiry, status
--   tb_drivers              school-owned, SEPARATE from tb_employees; driver_id is a varchar(20) business id {school short code}DR{nnn}
--                           generated by the app; photo_path is a key in the PRIVATE store (never a public URL)
--   tb_driver_areas         pickup areas of a driver: a pure mapping set, replaced wholesale on every save (rows are hard-deleted)
--   lut_roles row           'Driver' / DRIVER (inserted by name, no ids)
--   partial unique indexes  (Active rows only, status resolved BY NAME from lut_status, never a hard-coded id):
--                             area name per school, vehicle label per school, registration plate per school, DL number per school
--   plus a unique driver email per school (only when an email is given)
--
-- Safe to run twice (CREATE ... IF NOT EXISTS, ON CONFLICT DO NOTHING, guarded INSERT, DO block for the status-dependent indexes).
-- Needs the existing tb_schools, lut_status, lut_roles. Run it BEFORE starting an API build that contains these entities.
-- Nothing here touches tb_users, tb_employees or any fee table.
--
-- Decisions:
--  * "Hide this row" is status_id -> lut_status (Active / Inactive, stype 'general status'), exactly like employees. Deactivation rules
--    (an area or vehicle still assigned to an Active driver cannot be deactivated; a driver cannot be reactivated while its vehicle or an
--    assigned area is Inactive) are enforced in the service, with messages naming the item.
--  * Same-school integrity is enforced by the database: tb_drivers and tb_driver_areas reference tb_vehicles / tb_transport_areas / tb_drivers
--    through COMPOSITE (school_id, ...) foreign keys, so a driver can never point at another school's vehicle or area. A NULL vehicle_id skips the check.
--  * A vehicle may have several Active drivers (morning / evening): there is deliberately no uniqueness on tb_drivers.vehicle_id.
--  * Expiry badges (Expired / Expiring within 30 days / OK / Not set) are computed at read time, never stored.
--  * Driver photos: private storage, image types only, 2 MB (the same rule as Employee and Student photos).

BEGIN;

-- ---------------------------------------------------------------- global lookups (same shape as lut_gender)
CREATE TABLE IF NOT EXISTS public.lut_vehicle_type
(
    vehicle_type_id bigint       GENERATED ALWAYS AS IDENTITY,
    type_code       varchar(20)  NOT NULL,
    type_name       varchar(50)  NOT NULL,
    description     varchar(250),
    is_active       boolean      NOT NULL DEFAULT true,
    created_at      timestamptz  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at      timestamptz  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT lut_vehicle_type_pkey PRIMARY KEY (vehicle_type_id),
    CONSTRAINT uq_lut_vehicle_type_code UNIQUE (type_code),
    CONSTRAINT uq_lut_vehicle_type_name UNIQUE (type_name)
);
INSERT INTO public.lut_vehicle_type (type_code, type_name) VALUES
    ('BUS', 'Bus'), ('VAN', 'Van'), ('CAR', 'Car'), ('OTHER', 'Other')
ON CONFLICT (type_code) DO NOTHING;

CREATE TABLE IF NOT EXISTS public.lut_vehicle_ownership
(
    ownership_id    bigint       GENERATED ALWAYS AS IDENTITY,
    ownership_code  varchar(20)  NOT NULL,
    ownership_name  varchar(50)  NOT NULL,
    description     varchar(250),
    is_active       boolean      NOT NULL DEFAULT true,
    created_at      timestamptz  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at      timestamptz  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT lut_vehicle_ownership_pkey PRIMARY KEY (ownership_id),
    CONSTRAINT uq_lut_vehicle_ownership_code UNIQUE (ownership_code),
    CONSTRAINT uq_lut_vehicle_ownership_name UNIQUE (ownership_name)
);
INSERT INTO public.lut_vehicle_ownership (ownership_code, ownership_name) VALUES
    ('OWN', 'Own'), ('RENTED', 'Rented')
ON CONFLICT (ownership_code) DO NOTHING;

-- ---------------------------------------------------------------- areas
CREATE TABLE IF NOT EXISTS public.tb_transport_areas
(
    area_id        bigint         GENERATED ALWAYS AS IDENTITY,
    school_id      varchar(100)   NOT NULL,
    area_name      varchar(150)   NOT NULL,
    distance_km    numeric(6,2),
    transport_fee  numeric(10,2)  NOT NULL DEFAULT 0,   -- per period of the school's Transport fee type; no frequency column by decision
    remarks        varchar(500),
    status_id      integer        NOT NULL,
    created_at     timestamptz    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at     timestamptz    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT tb_transport_areas_pkey PRIMARY KEY (area_id),
    CONSTRAINT uq_tb_transport_areas_school_area UNIQUE (school_id, area_id),   -- target of the composite foreign keys
    CONSTRAINT fk_tb_transport_areas_school FOREIGN KEY (school_id) REFERENCES public.tb_schools (school_id),
    CONSTRAINT fk_tb_transport_areas_status FOREIGN KEY (status_id) REFERENCES public.lut_status (sid),
    CONSTRAINT chk_tb_transport_areas_amounts CHECK (transport_fee >= 0 AND (distance_km IS NULL OR distance_km >= 0))
);
CREATE INDEX IF NOT EXISTS idx_tb_transport_areas_school_id ON public.tb_transport_areas (school_id);

-- ---------------------------------------------------------------- vehicles
CREATE TABLE IF NOT EXISTS public.tb_vehicles
(
    vehicle_id           bigint        GENERATED ALWAYS AS IDENTITY,
    school_id            varchar(100)  NOT NULL,
    vehicle_label        varchar(50)   NOT NULL,   -- the school's own name, e.g. "Bus 3" (what the live map will show)
    registration_number  varchar(20)   NOT NULL,   -- plate; the app trims, upper-cases and removes inner spaces before saving
    vehicle_type_id      bigint        NOT NULL,
    ownership_id         bigint        NOT NULL,
    model_year           smallint,
    seating_capacity     smallint,
    owner_name           varchar(150),             -- only meaningful for Rented (validated in the service)
    owner_contact        varchar(20),
    last_service_date    date,
    puc_expiry_date      date,
    insurance_expiry_date date,
    status_id            integer       NOT NULL,
    created_at           timestamptz   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at           timestamptz   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT tb_vehicles_pkey PRIMARY KEY (vehicle_id),
    CONSTRAINT uq_tb_vehicles_school_vehicle UNIQUE (school_id, vehicle_id),
    CONSTRAINT fk_tb_vehicles_school    FOREIGN KEY (school_id)       REFERENCES public.tb_schools (school_id),
    CONSTRAINT fk_tb_vehicles_type      FOREIGN KEY (vehicle_type_id) REFERENCES public.lut_vehicle_type (vehicle_type_id),
    CONSTRAINT fk_tb_vehicles_ownership FOREIGN KEY (ownership_id)    REFERENCES public.lut_vehicle_ownership (ownership_id),
    CONSTRAINT fk_tb_vehicles_status    FOREIGN KEY (status_id)       REFERENCES public.lut_status (sid),
    CONSTRAINT chk_tb_vehicles_year     CHECK (model_year IS NULL OR model_year BETWEEN 1950 AND 2100),   -- "not in the future" is checked in the service
    CONSTRAINT chk_tb_vehicles_capacity CHECK (seating_capacity IS NULL OR seating_capacity > 0)
);
CREATE INDEX IF NOT EXISTS idx_tb_vehicles_school_id ON public.tb_vehicles (school_id);

-- ---------------------------------------------------------------- drivers (separate from tb_employees)
CREATE TABLE IF NOT EXISTS public.tb_drivers
(
    driver_id      varchar(20)   NOT NULL,   -- {school short code}DR{nnn}, generated by the app; reused as the login id (tb_users.org_user_id)
    school_id      varchar(100)  NOT NULL,
    full_name      varchar(150)  NOT NULL,
    mobile_number  varchar(20)   NOT NULL,
    email          varchar(150),
    address        text          NOT NULL,
    dl_number      varchar(30)   NOT NULL,
    dl_valid_upto  date          NOT NULL,
    vehicle_id     bigint,                   -- nullable; a vehicle MAY have several Active drivers
    photo_path     text,                     -- key in the PRIVATE store, e.g. SCH001/drivers/DPS001DR001/photo_<ts>.jpg
    status_id      integer       NOT NULL,
    created_at     timestamptz   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at     timestamptz   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT tb_drivers_pkey PRIMARY KEY (driver_id),
    CONSTRAINT uq_tb_drivers_school_driver UNIQUE (school_id, driver_id),
    CONSTRAINT fk_tb_drivers_school  FOREIGN KEY (school_id) REFERENCES public.tb_schools (school_id),
    CONSTRAINT fk_tb_drivers_vehicle FOREIGN KEY (school_id, vehicle_id) REFERENCES public.tb_vehicles (school_id, vehicle_id),
    CONSTRAINT fk_tb_drivers_status  FOREIGN KEY (status_id) REFERENCES public.lut_status (sid)
);
CREATE INDEX IF NOT EXISTS idx_tb_drivers_school_id ON public.tb_drivers (school_id);
CREATE INDEX IF NOT EXISTS idx_tb_drivers_vehicle   ON public.tb_drivers (vehicle_id);
-- an email belongs to one driver per school (blank emails are stored as NULL, so they never clash)
CREATE UNIQUE INDEX IF NOT EXISTS uq_tb_drivers_school_email ON public.tb_drivers (school_id, lower(email)) WHERE email IS NOT NULL;

-- ---------------------------------------------------------------- pickup areas (many-to-many)
CREATE TABLE IF NOT EXISTS public.tb_driver_areas
(
    driver_area_id bigint        GENERATED ALWAYS AS IDENTITY,
    school_id      varchar(100)  NOT NULL,
    driver_id      varchar(20)   NOT NULL,
    area_id        bigint        NOT NULL,
    created_at     timestamptz   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT tb_driver_areas_pkey PRIMARY KEY (driver_area_id),
    CONSTRAINT uq_tb_driver_areas_driver_area UNIQUE (driver_id, area_id),
    CONSTRAINT fk_tb_driver_areas_driver FOREIGN KEY (school_id, driver_id) REFERENCES public.tb_drivers (school_id, driver_id),
    CONSTRAINT fk_tb_driver_areas_area   FOREIGN KEY (school_id, area_id)   REFERENCES public.tb_transport_areas (school_id, area_id)
);
CREATE INDEX IF NOT EXISTS idx_tb_driver_areas_school_id ON public.tb_driver_areas (school_id);
CREATE INDEX IF NOT EXISTS idx_tb_driver_areas_area      ON public.tb_driver_areas (area_id);

-- ---------------------------------------------------------------- role (by name, no ids; same style as ADMISSION_STAFF)
INSERT INTO public.lut_roles (role_name, role_code, description, status_id)
SELECT 'Driver', 'DRIVER', 'School transport driver. Signs in only to the driver experience (built in a later stage); has no access to school data screens.',
       (SELECT sid FROM public.lut_status WHERE sname = 'Active' AND stype = 'general status')
WHERE NOT EXISTS (SELECT 1 FROM public.lut_roles WHERE role_code = 'DRIVER')
  AND EXISTS (SELECT 1 FROM public.lut_status WHERE sname = 'Active' AND stype = 'general status');

-- ---------------------------------------------------------------- "unique among Active" (the Active sid is looked up by name)
DO $$
DECLARE active_sid integer;
BEGIN
    SELECT sid INTO active_sid FROM public.lut_status WHERE sname = 'Active' AND stype = 'general status';
    IF active_sid IS NULL THEN RAISE EXCEPTION 'lut_status has no Active (general status) row'; END IF;
    EXECUTE format('CREATE UNIQUE INDEX IF NOT EXISTS uq_tb_transport_areas_active_name ON public.tb_transport_areas (school_id, lower(area_name))         WHERE status_id = %s', active_sid);
    EXECUTE format('CREATE UNIQUE INDEX IF NOT EXISTS uq_tb_vehicles_active_label       ON public.tb_vehicles        (school_id, lower(vehicle_label))        WHERE status_id = %s', active_sid);
    EXECUTE format('CREATE UNIQUE INDEX IF NOT EXISTS uq_tb_vehicles_active_plate       ON public.tb_vehicles        (school_id, upper(registration_number))  WHERE status_id = %s', active_sid);
    EXECUTE format('CREATE UNIQUE INDEX IF NOT EXISTS uq_tb_drivers_active_dl           ON public.tb_drivers         (school_id, upper(dl_number))            WHERE status_id = %s', active_sid);
END $$;

COMMIT;
